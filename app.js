let curCh = 0;
const readCfg = { font: 18, line: 2, night: false };

function openChapter(b, ci) {
  curBook = b;
  curCh = ci;
  const c = b.chs[ci];
  show("read");

  $("#rChTitle").textContent = c.t;
  $("#rByline").textContent = b.title + " · " + b.author;
  const body = $("#rBody");
  body.innerHTML = "";
  c.ps.forEach((p) => {
    const el = document.createElement("p");
    el.textContent = p;
    body.appendChild(el);
  });

  $("#prevCh").disabled = ci === 0;
  $("#nextCh").disabled = ci === b.chs.length - 1;
  $("#rPos").textContent = "第 " + (ci + 1) + " / " + b.chs.length + " 章";

  applyCfg();
  updateMarkBtn();

  /* 进度与最近阅读 */
  store.progress[b.id] = { ch: ci + 1, at: Date.now() };
  store.recent = [b.id].concat(store.recent.filter((x) => x !== b.id)).slice(0, 5);
  save();
}

function applyCfg() {
  $$("#rBody p").forEach((p) => {
    p.style.fontSize = readCfg.font + "px";
    p.style.lineHeight = readCfg.line;
  });
  $("#reader").classList.toggle("night", readCfg.night);
  $("#themeToggle").classList.toggle("on", readCfg.night);
}

$("#fontPlus").addEventListener("click", () => { readCfg.font = Math.min(24, readCfg.font + 1); applyCfg(); });
$("#fontMinus").addEventListener("click", () => { readCfg.font = Math.max(15, readCfg.font - 1); applyCfg(); });
$("#lineToggle").addEventListener("click", () => {
  readCfg.line = readCfg.line >= 2.2 ? 1.7 : Math.min(2.4, readCfg.line + 0.25);
  applyCfg();
});
$("#themeToggle").addEventListener("click", () => { readCfg.night = !readCfg.night; applyCfg(); });

