/* ═══════════ 书库渲染 + 朝代筛选 ═══════════ */
let curEra = "全部";

function bookCard(b, idx) {
  const li = document.createElement("li");
  li.className = "book";
  li.dataset.idx = "藏书 No." + String(idx + 1).padStart(2, "0");
  const p = store.progress[b.id];
  const pct = p ? Math.round((p.ch / b.chs.length) * 100) : 0;
  li.innerHTML =
    (pct ? "<i class='b-progress' style='width:" + pct + "%'></i>" : "") +
    "<h4>" + esc(b.title) + "</h4>" +
    "<p class='b-author'>" + esc(b.author) + "<i>" + esc(b.era) + " · " + esc(b.genre) + "</i></p>" +
    "<p class='b-sum'>" + esc(b.sum) + "</p>" +
    "<p class='b-meta'><span>" + b.chs.length + " 章</span><span>" +
    (b.words / 1000).toFixed(1) + " 千字</span>" +
    (p ? "<b>读到 " + esc(b.chs[p.ch - 1].t) + "</b>" : "<span>未启卷</span>") + "</p>";
  li.addEventListener("click", () => openBook(b));
  return li;
}

function renderHome() {
  $("#libStat").textContent = LIB.length + " 种 · " + TOTAL_CHS + " 章 · " +
    (TOTAL_WORDS / 1000).toFixed(1) + " 千字 · 全部公版";

  /* 朝代筛选条 */
  const eras = ["全部"].concat(Array.from(new Set(LIB.map((b) => b.era))));
  $("#filterBar").innerHTML = eras
    .map((e) => "<button class='chip" + (e === curEra ? " on" : "") + "' data-era='" + esc(e) + "'>" + esc(e) + "</button>")
    .join("");

  const list = curEra === "全部" ? LIB : LIB.filter((b) => b.era === curEra);
  const grid = $("#bookGrid");
  grid.innerHTML = "";
  list.forEach((b) => grid.appendChild(bookCard(b, LIB.indexOf(b))));
}

$("#filterBar").addEventListener("click", (e) => {
  const chip = e.target.closest(".chip");
  if (!chip) return;
  curEra = chip.dataset.era;
  renderHome();
});

