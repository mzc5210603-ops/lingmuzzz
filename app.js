/* 书签 */
function markKey(b, ci) { return b.id + ":" + ci; }
function updateMarkBtn() {
  const on = store.marks.some((m) => m.k === markKey(curBook, curCh));
  $("#markToggle").classList.toggle("on", on);
}
$("#markToggle").addEventListener("click", () => {
  const k = markKey(curBook, curCh);
  const exists = store.marks.some((m) => m.k === k);
  if (exists) store.marks = store.marks.filter((m) => m.k !== k);
  else store.marks.unshift({ k, book: curBook.id, ch: curCh, at: Date.now() });
  save();
  updateMarkBtn();
});

/* ═══════════ 全文检索 ═══════════ */
function search(kw) {
  const hits = [];
  LIB.forEach((b) => {
    b.chs.forEach((c, ci) => {
      c.ps.forEach((p) => {
        const idx = p.indexOf(kw);
        if (idx >= 0) {
          const from = Math.max(0, idx - 18);
          const frag = (from > 0 ? "……" : "") + p.slice(from, idx + kw.length + 24) + "……";
          hits.push({ b, ci, c, frag, idx });
        }
      });
    });
  });
  return hits;
}

function runSearch() {
  const kw = $("#q").value.trim();
  if (!kw) { show("home"); return; }
  const hits = search(kw);
  show("search");
  $("#sStat").textContent = "关键词「" + kw + "」· 命中 " + hits.length + " 处 · 涉及 " +
    new Set(hits.map((h) => h.b.id)).size + " 种";
  const ul = $("#sHits");
  ul.innerHTML = "";
  if (hits.length === 0) {
    ul.innerHTML = "<li style='cursor:default'><p class='hit-src'>未检得</p><p class='hit-txt'>全书库中没有这个字词，换一个试试。</p></li>";
    return;
  }
  hits.slice(0, 50).forEach((h) => {
    const li = document.createElement("li");
    const frag = esc(h.frag).replace(new RegExp(esc(kw), "g"), "<mark>" + esc(kw) + "</mark>");
    li.innerHTML =
      "<p class='hit-src'>" + esc(h.b.title) + " · " + esc(h.b.author) + "<i> " + esc(h.c.t) + "</i></p>" +
      "<p class='hit-txt'>" + frag + "</p>";
    li.addEventListener("click", () => openChapter(h.b, h.ci));
    ul.appendChild(li);
  });
}
$("#qGo").addEventListener("click", runSearch);
$("#q").addEventListener("keydown", (e) => { if (e.key === "Enter") runSearch(); });
$("#sBack").addEventListener("click", () => { renderHome(); show("home"); });

/* ═══════════ 书架视图 ═══════════ */
function renderShelf() {
  const recent = $("#recentList");
  recent.innerHTML = "";
  if (store.recent.length === 0) {
    recent.innerHTML = "<li class='book' style='cursor:default'><p class='b-sum'>还没有翻开过书。回「文库」挑一本吧。</p></li>";
  } else {
    store.recent.forEach((id) => {
      const b = LIB.find((x) => x.id === id);
      if (b) recent.appendChild(bookCard(b, LIB.indexOf(b)));
    });
  }

  const ul = $("#markList");
  ul.innerHTML = "";
  if (store.marks.length === 0) {
    ul.innerHTML = "<li style='cursor:default;padding:16px 6px;color:#8a857c;font-size:13px'>书签是空的。阅读时点右上「✩ 书签」收藏章节。</li>";
    return;
  }
  store.marks.forEach((m) => {
    const b = LIB.find((x) => x.id === m.book);
    if (!b) return;
    const li = document.createElement("li");
    const d = new Date(m.at);
    li.innerHTML =
      "<span class='m-book'>" + esc(b.title) + "</span><span class='m-ch'>" + esc(b.chs[m.ch].t) +
      "</span><i class='m-dots'></i><span class='m-time'>" +
      d.toLocaleDateString("zh-CN") + " " + d.toTimeString().slice(0, 5) + "</span>";
    li.addEventListener("click", () => openChapter(b, m.ch));
    ul.appendChild(li);
  });
}

